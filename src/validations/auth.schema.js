// นำเข้าเครื่องมือ 'zod' (ตัวสร้างกฎ) และตั้งชื่อเล่นให้มันว่า 'z' เพื่อให้เรียกใช้ง่ายๆ
import { z } from 'zod';

// ---------------------------------------------------------
// 1. กฎสำหรับการสมัครสมาชิก (Register)
// ---------------------------------------------------------
export const registerSchema = z.object({
  // กำหนดว่าข้อมูลต้องถูกส่งมาในก้อนที่ชื่อว่า 'body' (ซึ่งจะตรงกับ req.body ของ Express พอดี)
  body: z.object({
    
    // กฎของ email:
    // - z.string(): บังคับว่าต้องเป็นตัวอักษร 
    // - required_error: ถ้าไม่ส่งค่านี้มาเลย ให้ด่าว่า "กรุณากรอกอีเมล"
    // - .email(): บังคับว่ารูปแบบต้องมี @ และ .com ถ้าผิดให้ด่าว่า "รูปแบบอีเมลไม่ถูกต้อง"
    email: z.string({ required_error: "กรุณากรอกอีเมล" }).email("รูปแบบอีเมลไม่ถูกต้อง"),
    
    // กฎของ password:
    // - .min(6): บังคับว่าต้องพิมพ์มาอย่างน้อย 6 ตัวอักษร เพื่อความปลอดภัยตอนสร้างรหัส
    password: z.string({ required_error: "กรุณากรอกรหัสผ่าน" }).min(6, "รหัสผ่านต้องมีอย่างน้อย 6 ตัวอักษร"),
    
    // กฎของ name:
    // - .min(2): บังคับว่าชื่อต้องมีอย่างน้อย 2 ตัวอักษร (กันคนพิมพ์แค่ตัวอักษรเดียวมาป่วนระบบ)
    name: z.string({ required_error: "กรุณากรอกชื่อ" }).min(2, "ชื่อต้องมีอย่างน้อย 2 ตัวอักษร"),
    
    // กฎของ gender:
    // - .optional(): แปลว่า "จะมีหรือไม่มีก็ได้" ถ้าหน้าบ้านไม่ส่งมา ระบบก็จะไม่ Error และปล่อยผ่าน
    gender: z.string().optional(),
  }),
});

// ---------------------------------------------------------
// 2. กฎสำหรับการเข้าสู่ระบบ (Login)
// ---------------------------------------------------------
export const loginSchema = z.object({
  body: z.object({
    
    // กฎของ email ตอน Login (เหมือนตอนสมัครเป๊ะ เพราะต้องใช้เมลรูปแบบเดียวกันในการค้นหา)
    email: z.string({ required_error: "กรุณากรอกอีเมล" }).email("รูปแบบอีเมลไม่ถูกต้อง"),
    
    // กฎของ password ตอน Login:
    // - .min(1): ตรงนี้ไม่ได้บังคับ 6 ตัวแล้ว แต่บังคับแค่ว่า "ห้ามปล่อยช่องว่างเปล่า" 
    // (เพราะเราไม่ได้กำลังสร้างรหัสใหม่ เราแค่จะเอาข้อความนี้ไปเทียบกับในฐานข้อมูลเฉยๆ)
    password: z.string({ required_error: "กรุณากรอกรหัสผ่าน" }).min(1, "กรุณากรอกรหัสผ่าน"),
  }),
});